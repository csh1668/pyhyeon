mod module_codegen;

use crate::vm::bytecode::Module;

/// Generate a standalone `.rs` file that can be compiled with `rustc` directly.
///
/// The output contains:
/// 1. Header comment with original source
/// 2. `fn make_module() -> Module` (serialized bytecode)
/// 3. VM runtime boilerplate (included from build.rs output)
/// 4. `fn main()` entry point
pub fn generate_standalone(source: &str, path: &str, module: &Module) -> String {
    let template = include_str!(concat!(env!("OUT_DIR"), "/standalone_runtime.rs"));

    let mut out = String::new();

    // Header
    out.push_str("// ===== Pyhyeon to Rust =====\n");
    out.push_str("// This file was generated by Pyhyeon standalone mode.\n");
    out.push_str("// https://github.com/csh1668/pyhyeon`\n");
    out.push_str("\n");

    // Original source as comments
    out.push_str(&format!("// ===== Original Source ({}) =====\n", path));
    for line in source.lines() {
        out.push_str(&format!("// {}\n", line));
    }
    out.push_str("// ===== End of Source =====\n\n");

    // VM Runtime boilerplate (from build.rs template)
    out.push_str("// ===== Boilerplate (VM Runtime) =====\n");
    out.push_str(template);
    out.push('\n');

    // Bytecode (make_module function)
    out.push_str("// ===== Bytecode =====\n");
    out.push_str(&module_codegen::codegen_module(module));
    out.push('\n');

    // main() entry point
    out.push_str(
        r#"fn main() {
    let mut module = make_module();
    let mut vm = Vm::new();
    if let Err(e) = vm.run(&mut module) {
        eprintln!("Runtime Error: {:?}: {}", e.kind, e.message);
        std::process::exit(1);
    }
}
"#,
    );

    out
}
